    print(f"\n⚙️ Running Routine: '{action_name.upper()}'")
 
    for cmd in commands:
        json_payload = json.dumps(cmd) + "\r\n"
        serial_obj.write(json_payload.encode('utf-8'))
 
        if cmd["T"] == 101:
            time.sleep(2.0)  
        else:
            time.sleep(1.5 if cmd["spd"] > 700 else 2.1)
 
        while serial_obj.in_waiting:
            serial_obj.readline()
 
    print(f"✅ Routine '{action_name.upper()}' completed.")
 
